<div class="container">

    <section>
        <h2><span class="icon">🏫</span> 1. Quiénes somos</h2>
        <p>
            PuntoKampus es una plataforma de marketplace universitario operada por estudiantes de la
            <strong>Universidad Técnica de Babahoyo (UTB)</strong>. Nuestra misión es conectar a vendedores
            y compradores dentro del campus de forma segura, práctica y transparente.
        </p>
        <p style="margin-top:0.75rem;">
            Para consultas de privacidad puedes escribirnos a:
            <a href="mailto:privacidad@puntokampus.utb.edu.ec">privacidad@puntokampus.utb.edu.ec</a>
        </p>
    </section>

    <section>
        <h2><span class="icon">📋</span> 2. Datos que recopilamos</h2>
        <p>Recopilamos únicamente los datos necesarios para operar el servicio:</p>
        <ul>
            <li><strong>Correo institucional UTB</strong> — para autenticarte y comunicarnos contigo.</li>
            <li><strong>Nombre y apellidos</strong> — para identificarte dentro de la plataforma.</li>
            <li><strong>Número de WhatsApp</strong> — para que compradores contacten a vendedores directamente.</li>
            <li><strong>Código de estudiante, facultad, carrera y semestre</strong> — de forma opcional, para personalizar tu experiencia.</li>
            <li><strong>Fotos de productos</strong> — imágenes que tú mismo subes para tu tienda.</li>
            <li><strong>Comprobantes de pago</strong> — para verificar solicitudes de plan Premium (almacenados de forma privada).</li>
            <li><strong>Registros de pedidos</strong> — historial de transacciones dentro de la plataforma.</li>
        </ul>
    </section>

    <section>
        <h2><span class="icon">🎯</span> 3. Para qué usamos tus datos</h2>
        <ul>
            <li>Autenticarte con tu correo UTB de forma segura (sin contraseñas).</li>
            <li>Mostrar tu tienda y productos a otros estudiantes del campus.</li>
            <li>Permitir que compradores contacten vendedores por WhatsApp.</li>
            <li>Gestionar pedidos, estados y notificaciones.</li>
            <li>Verificar la identidad de estudiantes que solicitan el plan Premium.</li>
            <li>Detectar y gestionar reportes de comportamiento inapropiado.</li>
            <li>Mejorar la plataforma con estadísticas agregadas y anónimas.</li>
        </ul>
    </section>

    <section>
        <h2><span class="icon">👥</span> 4. Quién puede ver tu información</h2>
        <ul>
            <li><strong>Otros estudiantes UTB:</strong> solo ven tu nombre, nombre de tienda, productos y número de WhatsApp si tienes una tienda activa.</li>
            <li><strong>El equipo de administración de PuntoKampus:</strong> puede ver todos los datos para gestión y moderación.</li>
            <li><strong>Terceros:</strong> <em>no compartimos tus datos con terceros</em> ni los vendemos a ninguna empresa.</li>
            <li>Los comprobantes de pago son privados y solo los ve el equipo administrativo.</li>
        </ul>
    </section>

    <section>
        <h2><span class="icon">⏱️</span> 5. Cuánto tiempo guardamos tus datos</h2>
        <ul>
            <li><strong>Tokens de sesión:</strong> hasta el fin del periodo académico activo o hasta que cierres sesión.</li>
            <li><strong>Códigos de acceso:</strong> 10 minutos de vigencia, luego son descartados.</li>
            <li><strong>Comprobantes Premium resueltos:</strong> eliminados automáticamente tras 30 días de resolución.</li>
            <li><strong>Datos de cuenta:</strong> mientras tengas una cuenta activa. Al eliminar tu cuenta, tus datos se anonimizan de forma inmediata.</li>
        </ul>
    </section>

    <section>
        <h2><span class="icon">⚖️</span> 6. Tus derechos</h2>
        <p>Como usuario de PuntoKampus tienes derecho a:</p>
        <ul>
            <li><strong>Acceder</strong> a tus datos en cualquier momento desde tu perfil en la app.</li>
            <li><strong>Corregir</strong> tus datos actualizando tu perfil.</li>
            <li><strong>Eliminar</strong> tu cuenta y datos en cualquier momento — ver sección siguiente.</li>
            <li><strong>Oponerte</strong> al uso de tus datos para fines no esenciales.</li>
        </ul>
        <p style="margin-top:0.75rem;">
            Para ejercer cualquiera de estos derechos, contáctanos en
            <a href="mailto:privacidad@puntokampus.utb.edu.ec">privacidad@puntokampus.utb.edu.ec</a>.
        </p>
    </section>

    <section>
        <h2><span class="icon">🗑️</span> 7. Cómo eliminar tu cuenta</h2>
        <p>
            Puedes solicitar la eliminación de tu cuenta y datos personales en cualquier momento.
            Al eliminar tu cuenta:
        </p>
        <ul>
            <li>Tus datos personales serán <strong>anonimizados de inmediato</strong> (nombre, correo, teléfono).</li>
            <li>Tus pedidos pendientes como vendedor serán cancelados automáticamente.</li>
            <li>Tus fotos de productos y comprobantes serán eliminados del servidor.</li>
            <li>Tu sesión será cerrada en todos los dispositivos.</li>
        </ul>
        <p style="margin-top:0.75rem;">
            Puedes hacerlo desde la app PuntoKampus (Perfil → Eliminar cuenta) o desde
            <a href="/borrar-cuenta">esta página</a>.
        </p>
    </section>

    <section>
        <h2><span class="icon">🔒</span> 8. Seguridad</h2>
        <ul>
            <li>La comunicación se realiza siempre por HTTPS.</li>
            <li>Los tokens de sesión se almacenan hasheados en el servidor.</li>
            <li>Los comprobantes de pago se guardan en almacenamiento privado (no accesible públicamente).</li>
            <li>Aplicamos límites de intentos para prevenir accesos no autorizados.</li>
        </ul>
    </section>

    <section>
        <h2><span class="icon">📝</span> 9. Cambios a esta política</h2>
        <p>
            Podemos actualizar esta política ocasionalmente. Cuando hagamos cambios significativos,
            te notificaremos por correo institucional o mediante un aviso en la app.
            La fecha de última actualización aparece abajo.
        </p>
